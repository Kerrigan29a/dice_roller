"""Generate native constants from the one maintained oracle catalog."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
tables = json.loads((ROOT / "data/tables.json").read_text())
version = (ROOT / "VERSION").read_text().strip()
quoted = lambda value: json.dumps(value, ensure_ascii=False)

gleam = "// Generated by scripts/generate_tables.py; edit data/tables.json.\npub const entries = [\n"
for name, columns in tables.items():
    gleam += "  #(" + quoted(name) + ", " + quoted(columns) + "),\n"
gleam += "]\n"
(ROOT / "gleam/src/dice_roller/table_data.gleam").write_text(gleam)

elm = """-- Generated by scripts/generate_tables.py; edit data/tables.json.
module Tables exposing (tables)

import Array
import Dict
import Random

pick words =
    let
        choices = Array.fromList words
    in
    Random.int 0 (Array.length choices - 1)
        |> Random.map (\\index -> Array.get index choices |> Maybe.withDefault "")

combine columns =
    List.foldr (Random.map2 (::) << pick) (Random.constant []) columns
        |> Random.map (String.join " ")

tables =
    Dict.fromList
        [ """
elm += "\n        , ".join("( " + quoted(name) + ", combine " + quoted(columns) + " )" for name, columns in tables.items())
elm += "\n        ]\n"
target = ROOT / "elm/generated"
target.mkdir(exist_ok=True)
(target / "Tables.elm").write_text(elm)
(target / "Version.elm").write_text(f'module Version exposing (value)\n\nvalue : String\nvalue = "{version}"\n')
target = ROOT / "go/internal/roller"
target.mkdir(parents=True, exist_ok=True)
(target / "tables.json").write_text(json.dumps(tables, separators=(",", ":")))
(target / "version.go").write_text(f'// Generated from VERSION.\npackage roller\nconst Version = "{version}"\n')
(ROOT / "gleam/src/dice_roller/build_info.gleam").write_text(f'// Generated from VERSION.\npub const version = "{version}"\n')
